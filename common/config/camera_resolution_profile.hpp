#ifndef CAMERA_RESOLUTION_PROFILE_HPP
#define CAMERA_RESOLUTION_PROFILE_HPP

/**
 * 相机输出分辨率档位（编译期宏开关）：
 *   - 1080: 1080x1280
 *   - 1024: 1024x1280
 *
 * 如需切换档位，只改这一处即可：
 *   #define UPC_CAMERA_WIDTH_PROFILE 1024
 */
#ifndef UPC_CAMERA_WIDTH_PROFILE
#define UPC_CAMERA_WIDTH_PROFILE 1080
#endif

#if UPC_CAMERA_WIDTH_PROFILE == 1080
#define UPC_CAMERA_STREAM_WIDTH 1080u
#elif UPC_CAMERA_WIDTH_PROFILE == 1024
#define UPC_CAMERA_STREAM_WIDTH 1024u
#else
#error "UPC_CAMERA_WIDTH_PROFILE must be 1080 or 1024"
#endif

#define UPC_CAMERA_STREAM_HEIGHT 1280u

#endif /* CAMERA_RESOLUTION_PROFILE_HPP */
