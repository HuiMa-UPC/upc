#!/usr/bin/env python3
"""生成首页背景合成层（RGB565 lv_image_dsc_t home_bg）。

图源为 Figma 设计稿 fileKey DNrr8MiRglxIiof1MBk4TY 的背景层节点 3540:14474
（整机渲染 + 暗色渐变，不含任何 UI 元素）。该层已把设备按设计定位、右侧压暗，
运行时以 LV_IMAGE_ALIGN_COVER 铺满内容区，使右侧 CABIN 文字落在暗区、不与设备重叠。

输入：
    tools/_bg_tmp/home_bg_src.png   （从 Figma 导出的 1280×800 PNG）
输出：
    app/ui/lib/assets/src/home_bg.c （单独文件，符号 home_bg；声明仍在 home_assets.h）

用法：
    python3 tools/gen_home_bg.py
"""
import os

from PIL import Image

# 目标尺寸：保设计比例 1.6（1280:800），比旧图 1008×700 略省内存，COVER 兜底缩放。
OUT_W = 1024
OUT_H = 640

# 设备整体左移量（输出像素）。设备原右缘约 71%，左移 ~72px(≈7%) 后退到 ~64%，
# 给右侧 28% 面板（左缘 ~70%）腾出暗区，避免重叠。上屏后可微调此值。
SHIFT_LEFT_PX = 72


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    src_png = os.path.join(root, "tools", "_bg_tmp", "home_bg_src.png")
    out_c = os.path.join(root, "app", "ui", "lib", "assets", "src", "home_bg.c")

    im = Image.open(src_png).convert("RGBA").resize((OUT_W, OUT_H), Image.LANCZOS)
    # 合成到不透明底（设计外底色 #272628），消除可能的半透明像素。
    bg = Image.new("RGBA", im.size, (0x27, 0x26, 0x28, 255))
    im = Image.alpha_composite(bg, im).convert("RGB")

    # 设备左移：丢弃最左 SHIFT_LEFT_PX（纯暗墙），整体左移；右侧暴露区用场景
    # 最右一列做水平延拓（墙→地过渡自然延续），避免生硬竖直拼缝。
    if SHIFT_LEFT_PX > 0:
        shifted = Image.new("RGB", (OUT_W, OUT_H), (0x27, 0x26, 0x28))
        body = im.crop((SHIFT_LEFT_PX, 0, OUT_W, OUT_H))   # 左移后的主体
        shifted.paste(body, (0, 0))
        edge = im.crop((OUT_W - 1, 0, OUT_W, OUT_H)).resize((SHIFT_LEFT_PX, OUT_H))
        shifted.paste(edge, (OUT_W - SHIFT_LEFT_PX, 0))
        im = shifted

    px = im.load()
    lines = []
    for y in range(OUT_H):
        row = []
        for x in range(OUT_W):
            r, g, b = px[x, y]
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            row.append(str(v & 0xFF))          # 低字节在前（小端，与旧图一致）
            row.append(str((v >> 8) & 0xFF))
        lines.append("    " + ",".join(row) + ",")
    body = "\n".join(lines)

    data_size = OUT_W * OUT_H * 2
    c = (
        "/* AUTO-GENERATED by tools/gen_home_bg.py — do not edit by hand.\n"
        " * 源：Figma 3540:14474（首页背景层：整机 + 暗色渐变）。 */\n"
        '#include "lvgl_wrap.hpp"\n\n'
        f"static const uint8_t home_bg_map[] = {{\n{body}\n}};\n\n"
        "const lv_image_dsc_t home_bg = {\n"
        "    .header = {\n"
        "        .magic = LV_IMAGE_HEADER_MAGIC,\n"
        "        .cf = LV_COLOR_FORMAT_RGB565,\n"
        "        .flags = 0,\n"
        f"        .w = {OUT_W},\n"
        f"        .h = {OUT_H},\n"
        f"        .stride = {OUT_W * 2},\n"
        "        .reserved_2 = 0,\n"
        "    },\n"
        f"    .data_size = {data_size},\n"
        "    .data = home_bg_map,\n"
        "};\n"
    )
    with open(out_c, "w") as f:
        f.write(c)
    print(f"wrote {out_c} ({OUT_W}x{OUT_H}, {data_size} bytes RGB565)")


if __name__ == "__main__":
    main()
