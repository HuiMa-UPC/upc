# 输出顺序（决定 .c/.h 中的排列）
ORDER = ["home", "switch", "cabin", "aqi", "humidity", "pressure"]


def rasterize_alpha(inner: str):
    # 统一描边：白色、1.6px（32 坐标系）、圆角端；填充默认 none。
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" '
        f'viewBox="{VIEWBOX}" fill="none">'
        f'<g fill="none" stroke="white" stroke-width="1.6" '
        f'stroke-linecap="round" stroke-linejoin="round">{inner}</g>'
        f'</svg>'
    )
    png = cairosvg.svg2png(bytestring=svg.encode("utf-8"),
                           output_width=SIZE, output_height=SIZE)
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    return list(img.getchannel("A").getdata())


def emit_map(name: str, alpha) -> str:
    lines = []
    for row in range(SIZE):
        chunk = alpha[row * SIZE:(row + 1) * SIZE]
        lines.append("    " + ",".join(str(v) for v in chunk) + ",")
    body = "\n".join(lines)
    return (f"static const uint8_t ic_{name}_map[] = {{\n"
            f"{body}\n}};\n\n")


def emit_dsc(name: str) -> str:
    return (f"const lv_image_dsc_t ic_{name} = {{\n"
            f"    .header = {{\n"
            f"        .magic = LV_IMAGE_HEADER_MAGIC,\n"
            f"        .cf = LV_COLOR_FORMAT_A8,\n"
            f"        .flags = 0,\n"
            f"        .w = {SIZE},\n"
            f"        .h = {SIZE},\n"
            f"        .stride = {SIZE},\n"
            f"        .reserved_2 = 0,\n"
            f"    }},\n"
            f"    .data_size = {SIZE * SIZE},\n"
            f"    .data = ic_{name}_map,\n"
            f"}};\n\n")


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    src = os.path.join(root, "app", "ui", "lib", "assets", "src", "home_metric_icons.c")
    inc = os.path.join(root, "app", "ui", "lib", "assets", "inc", "home_metric_icons.h")

    c = ['/* AUTO-GENERATED by tools/gen_home_metric_icons.py — do not edit by hand. */',
         '#include "lvgl_wrap.hpp"', '', '']
    c = "\n".join(c)
    for name in ORDER:
        alpha = rasterize_alpha(ICONS[name])
        c += emit_map(name, alpha)
        c += emit_dsc(name)

    h = ['/* AUTO-GENERATED by tools/gen_home_metric_icons.py — do not edit by hand. */',
         '#ifndef HOME_METRIC_ICONS_H', '#define HOME_METRIC_ICONS_H', '',
         '#include "lvgl_wrap.hpp"', '', '#ifdef __cplusplus',
         'extern "C" {', '#endif', '']
    for name in ORDER:
        h.append(f"extern const lv_image_dsc_t ic_{name};")
    h += ['', '#ifdef __cplusplus', '}', '#endif', '', '#endif', '']
    h = "\n".join(h)

    with open(src, "w") as f:
        f.write(c)
    with open(inc, "w") as f:
        f.write(h)
    print(f"wrote {src}")
    print(f"wrote {inc}")


if __name__ == "__main__":
    main()
