#!/usr/bin/env python3
"""生成通知徽标图标（A8 lv_image_dsc_t），供消息页列表与左下通知浮层的等级徽标使用。

图源直接取自 Figma 设计稿（fileKey DNrr8MiRglxIiof1MBk4TY）导出的 SVG：
    tools/_badge_svg/badge_alert.svg   3058:7234  警告三角（红/橙/黄档徽标）
    tools/_badge_svg/badge_info.svg    3058:7059  对话气泡（info 档徽标）

**为什么每档屏各出一版**：徽标边长是 USER_PRINT_BADGE_SZ*2，图标取其 9/16，
三档屏分别落在 14 / 18 / 27 px。原先只有一张 36px 位图，运行时靠
lv_image_set_scale 缩放，1024 档是 0.39 倍——细描边的三角被采样糊成一团。
按目标尺寸直接从矢量栅格化后，ui_user_make_icon_img() 里 target == src_sz，
缩放整段被跳过，每档都是逐像素干净的。

改了尺寸表就要同步 ui_message_store.cpp 的 ui_message_severity_icon()。

用法：
    python3 tools/gen_notice_badge_icons.py
输出：
    app/ui/lib/assets/src/notice_badge_icons.c
    app/ui/lib/assets/inc/notice_badge_icons.h
"""
import io
import os

import cairosvg
from PIL import Image

# 目标边长 = 徽标边长(USER_PRINT_BADGE_SZ*2) * 9/16，见 ui_theme.cpp 三档 profile。
SIZES = {
    14: "1024",   # USER_PRINT_BADGE_SZ 13 → 徽标 26
    18: "1280",   # 16 → 32（与稿 3058:7233 的 32/18 完全一致）
    27: "1920",   # 24 → 48
}

# 符号名前缀 -> 源 SVG。前缀不能撞 home_metric_icons.h 里的 ic_badge_*
# （那是打印六态徽标，另一回事）。
ICONS = {
    "ic_notice_alert": "badge_alert.svg",
    "ic_notice_info":  "badge_info.svg",
}


def rasterize_alpha(svg_path: str, size: int):
    """按目标边长栅格化，取 alpha 通道。稿里的描边宽度随 viewBox 一起缩放，
    小尺寸下线会变细但不会断——这正是矢量直栅相对位图缩放的好处。"""
    png = cairosvg.svg2png(url=svg_path, output_width=size, output_height=size)
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    return list(img.getchannel("A").getdata())


def emit_map(sym: str, alpha, size: int) -> str:
    lines = []
    for row in range(size):
        chunk = alpha[row * size:(row + 1) * size]
        lines.append("    " + ",".join(str(v) for v in chunk) + ",")
    body = "\n".join(lines)
    return f"static const uint8_t {sym}_map[] = {{\n{body}\n}};\n\n"


def emit_dsc(sym: str, size: int) -> str:
    return (f"const lv_image_dsc_t {sym} = {{\n"
            f"    .header = {{\n"
            f"        .magic = LV_IMAGE_HEADER_MAGIC,\n"
            f"        .cf = LV_COLOR_FORMAT_A8,\n"
            f"        .flags = 0,\n"
            f"        .w = {size},\n"
            f"        .h = {size},\n"
            f"        .stride = {size},\n"
            f"        .reserved_2 = 0,\n"
            f"    }},\n"
            f"    .data_size = {size * size},\n"
            f"    .data = {sym}_map,\n"
            f"}};\n\n")


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    svg_dir = os.path.join(root, "tools", "_badge_svg")
    src = os.path.join(root, "app", "ui", "lib", "assets", "src", "notice_badge_icons.c")
    inc = os.path.join(root, "app", "ui", "lib", "assets", "inc", "notice_badge_icons.h")

    banner = "/* AUTO-GENERATED by tools/gen_notice_badge_icons.py — do not edit by hand. */"

    c = f'{banner}\n#include "lvgl_wrap.hpp"\n\n\n'
    h = [banner, "#ifndef NOTICE_BADGE_ICONS_H", "#define NOTICE_BADGE_ICONS_H", "",
         '#include "lvgl_wrap.hpp"', "", "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]

    for prefix, svg_name in ICONS.items():
        svg_path = os.path.join(svg_dir, svg_name)
        for size, profile in SIZES.items():
            sym = f"{prefix}_{size}"
            alpha = rasterize_alpha(svg_path, size)
            c += emit_map(sym, alpha, size)
            c += emit_dsc(sym, size)
            h.append(f"extern const lv_image_dsc_t {sym};   /* {profile} 档 */")
        h.append("")

    h += ["#ifdef __cplusplus", "}", "#endif", "", "#endif", ""]

    with open(src, "w") as f:
        f.write(c)
    with open(inc, "w") as f:
        f.write("\n".join(h))
    print(f"wrote {src}")
    print(f"wrote {inc}")


if __name__ == "__main__":
    main()
