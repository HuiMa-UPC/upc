#!/usr/bin/env python3
"""生成打印前置流程插图（ARGB8888 lv_image_dsc_t），供 control.cpp 弹窗使用。

图源为 Figma 设计稿 fileKey DNrr8MiRglxIiof1MBk4TY 的放版/开门插画节点：
    img_plate_single  2672:4915  「已放入」蓝色打印版在槽内
    img_plate_double  2672:4865  「未放入」打印版悬空 + 蓝色下箭头（DoorOpened 也复用）
    img_device_unlock 2566:5241  开门态：设备 + 蓝色箭头
    img_device_lock   3251:14574 关门确认态：设备 + 蓝色箭头

输入（需先用 download_assets 导出 PNG 到该目录）：
    tools/_pf_tmp/{plate_single,plate_double,device_unlock,device_lock}.png
输出：
    app/ui/lib/assets/src/print_flow_img.c

ARGB8888 数据按 LVGL 约定的小端字节序存储：B,G,R,A。

用法：
    python3 tools/gen_print_flow_assets.py
"""
import os

from PIL import Image

# name -> (源 PNG, 目标宽, 目标高)。
# plate_* 供选择/未放入卡片（保持 380×240）；device_*/door_opened 供舱门弹窗顶部
# 满宽大图（496×321，对齐 Figma 2566:5240/5306/5430 的图框，避免升采样发糊）。
ASSETS = [
    ("img_plate_single",  "plate_single.png",  380, 240),
    ("img_plate_double",  "plate_double.png",  380, 240),
    ("img_device_unlock", "device_unlock.png", 496, 321),
    ("img_door_opened",   "door_opened.png",   496, 321),
    ("img_device_lock",   "device_lock.png",   496, 321),
]


def emit(name: str, png: str, w: int, h: int, tmp_dir: str) -> str:
    im = Image.open(os.path.join(tmp_dir, png)).convert("RGBA").resize((w, h), Image.LANCZOS)
    px = im.load()
    lines = []
    for y in range(h):
        row = []
        for x in range(w):
            r, g, b, a = px[x, y]
            row.extend((str(b), str(g), str(r), str(a)))   # ARGB8888 小端：B,G,R,A
        lines.append("    " + ",".join(row) + ",")
    body = "\n".join(lines)
    data_size = w * h * 4
    return (
        f"static const uint8_t {name}_map[] = {{\n{body}\n}};\n\n"
        f"const lv_image_dsc_t {name} = {{\n"
        f"    .header = {{\n"
        f"        .magic = LV_IMAGE_HEADER_MAGIC,\n"
        f"        .cf = LV_COLOR_FORMAT_ARGB8888,\n"
        f"        .flags = 0,\n"
        f"        .w = {w},\n"
        f"        .h = {h},\n"
        f"        .stride = {w * 4},\n"
        f"        .reserved_2 = 0,\n"
        f"    }},\n"
        f"    .data_size = {data_size},\n"
        f"    .data = {name}_map,\n"
        f"}};\n\n"
    )


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    tmp_dir = os.path.join(root, "tools", "_pf_tmp")
    out_c = os.path.join(root, "app", "ui", "lib", "assets", "src", "print_flow_img.c")

    c = '/* AUTO-GENERATED by tools/gen_print_flow_assets.py — do not edit by hand. */\n'
    c += '#include "lvgl_wrap.hpp"\n\n'
    for name, png, w, h in ASSETS:
        c += emit(name, png, w, h, tmp_dir)

    with open(out_c, "w") as f:
        f.write(c)
    print(f"wrote {out_c}")


if __name__ == "__main__":
    main()
